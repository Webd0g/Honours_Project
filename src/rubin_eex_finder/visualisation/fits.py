from rubin_eex_finder.models.excess_power_law import power_law_model


def bazin_curve(
    t: np.ndarray,
    amplitude: float,
    t0: float,
    tau_rise: float,
    tau_fall: float,
    baseline: float,
) -> np.ndarray:
    """The Bazin et al. (2009) model, used here just to draw the fitted curve
    for visual inspection (feets returns the fitted parameters, not the curve
    itself)."""
    return (
        amplitude * np.exp(-(t - t0) / tau_fall) / (1 + np.exp(-(t - t0) / tau_rise))
        + baseline
    )


def plot_bazin_fit_single_object(
    group_df: pd.DataFrame,
    band: str,
    fit_result: dict,
    diaObjectId: str,
    output_path: Path,
) -> None:
    """
    Quick visual check: plots the band's actual flux data points with the fitted
    Bazin curve overlaid, so the fit can be sanity-checked by eye.
    """

    band_df = group_df.filter(
        (pl.col("r:band") == band) & (pl.col("r:psfFlux") > 0)
    ).sort("r:midpointMjdTai")

    t = band_df["r:midpointMjdTai"].to_numpy().astype(np.float64)
    flux = band_df["r:psfFlux"].to_numpy().astype(np.float64)
    flux_err = band_df["r:psfFluxErr"].to_numpy().astype(np.float64)

    t_fine = np.linspace(t.min(), t.max(), 300)
    fit_flux = bazin_curve(
        t_fine,
        fit_result["amplitude"],
        fit_result["reference_time"],
        fit_result["rise_time"],
        fit_result["fall_time"],
        fit_result["baseline"],
    )

    fig, ax = plt.subplots(figsize=(10, 6))
    ax.errorbar(
        t,
        flux,
        yerr=flux_err,
        fmt="o",
        color="darkred",
        label=f"{band}-band data",
        capsize=3,
        markersize=5,
    )
    ax.plot(
        t_fine,
        fit_flux,
        "--",
        color="purple",
        label=f"Bazin fit (chi2={fit_result['reduced_chi2']:.2f})",
    )
    ax.set_xlabel("MJD")
    ax.set_ylabel("Flux (nanojansky)")
    ax.set_title(f"Bazin fit - {diaObjectId} ({band}-band)")
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(output_path / f"{diaObjectId}_{band}_band.png")
    print(f"saved the plot of object {diaObjectId}")
    plt.close(fig)


def plot_bazin_fit_batch(
    dict_path: Path,
    csv_path: Path,
    light_curve_data_path: Path,
    band: str,
    output_path: Path,
) -> None:
    """
    Plots the light curve of the objects data in the band requested and overlays the fitted Bazin
    line on the plot.

    This is to check that the Bazin fit is both doing what we want it to do and gives up data for visual
    inspection which is both valuable and neccessary.
    """

    objects = pl.read_csv(
        csv_path,
        schema_overrides={"r:diaObjectId": pl.String},
        columns=["r:diaObjectId"],
    )["r:diaObjectId"].to_list()
    light_curve_data = pl.read_parquet(light_curve_data_path)
    light_curve_data_filtered = light_curve_data.filter(
        pl.col("r:diaObjectId").cast(pl.Utf8).is_in(objects)
    )

    bazin_df = pl.read_csv(dict_path, schema_overrides={"r:diaObjectId": pl.String})
    bazin_fit_dict = (
        bazin_df.to_pandas().set_index("r:diaObjectId").to_dict(orient="index")
    )

    groups = {
        key[0]: group_df
        for key, group_df in light_curve_data_filtered.group_by(
            "r:diaObjectId", maintain_order=True
        )
    }

    for object_id in objects:
        group_df = groups.get(object_id)
        if group_df is None:
            continue
        fit_result = bazin_fit_dict.get(object_id)
        print(fit_result)
        if fit_result is None:
            print(
                f"Object {object_id} did not have any data in that band and couldn't be fitted to and thus won't be plotted."
            )
            continue
        if plot_bazin_fit_single_object(
            group_df, band, fit_result, object_id, output_path
        ):
            print(f"{object_id} has been plotted.")


# This code for the plotting function was generated by ChatGPT using the prompt "So I ran the code and it identified four objects that could be EEx candidates, I check the plots and three are obvious contaminants and one is a genuine candidate for EEx. The plot is attached. Now we move to the custom code for the plots, this shouldn't be too hard as we can load this single png in and use polars to extract the t_fd and add axvlines on the plots at those points and modify the opacity of the points right?"
def plot_eex_salt_candidate_diagnostic(
    object_df_path: Path,
    light_curve_data_path: Path,
    plot_output_path: Path | None = None,
) -> None:
    """Generate the custom plot for the few SALT EEx objects that were succesfully detected.

    Args:
        object_df_path (Path): Path to the CSV that hosts the passing objects.
        plot_output_path (Path | None, optional): Path to where the plot will go when made. Defaults to None.
    """

    BAND_MAP = {
        "u": "lsstu",
        "g": "lsstg",
        "r": "lsstr",
        "i": "lssti",
        "z": "lsstz",
        "y": "lssty",
    }

    BAND_COLORS = {
        "u": "blue",
        "g": "dodgerblue",
        "r": "mediumspringgreen",
        "i": "gold",
        "z": "orangered",
        "y": "firebrick",
    }

    object_df = pl.read_csv(
        object_df_path,
        schema_overrides={
            "r:diaObjectId": pl.String,
            "z_used": pl.Float64,
            "t0": pl.Float64,
            "x0": pl.Float64,
            "x1": pl.Float64,
            "c": pl.Float64,
            "t_fd": pl.Float64,
        },
    ).filter(pl.col("r:diaObjectId") == "170019716323082348")

    light_curve_data = (
        pl.read_parquet(
            light_curve_data_path,
            columns=[
                "r:diaObjectId",
                "r:band",
                "r:psfFlux",
                "r:psfFluxErr",
                "r:midpointMjdTai",
                "r:diaSourceId",
            ],
        )
        .with_columns(pl.col("r:diaObjectId").cast(pl.String))
        .filter(
            pl.col("r:diaObjectId").is_in(object_df["r:diaObjectId"])
            & pl.col("r:psfFlux").is_finite()
            & pl.col("r:psfFluxErr").is_finite()
            & pl.col("r:midpointMjdTai").is_finite()
            & (pl.col("r:psfFluxErr") > 0)
        )
    )

    light_curve_data = light_curve_data.join(
        object_df.select("r:diaObjectId", "z_used", "t0", "x0", "x1", "c", "t_fd"),
        on="r:diaObjectId",
        how="inner",
    )

    groups = {
        key[0]: group_df.sort("r:midpointMjdTai")
        for key, group_df in light_curve_data.group_by(
            "r:diaObjectId",
            maintain_order=True,
        )
    }

    for object_id, group_df in groups.items():
        z_used = group_df["z_used"].item(0)
        t0 = group_df["t0"].item(0)
        x0 = group_df["x0"].item(0)
        x1 = group_df["x1"].item(0)
        c = group_df["c"].item(0)
        t_fd = group_df["t_fd"].item(0)

        model = sncosmo.Model(source="salt3")

        model.set(z=z_used, t0=t0, x0=x0, x1=x1, c=c)

        excess_start = t_fd
        excess_end = t_fd - 4.0

        group_df = group_df.with_columns(
            (pl.col("r:midpointMjdTai") - t0).alias("phase_obs"),
            ((pl.col("r:midpointMjdTai") - t0) / (1 + z_used)).alias("phase_rest"),
            (
                (pl.col("r:midpointMjdTai") >= excess_start)
                & (pl.col("r:midpointMjdTai") <= excess_end)
            ).alias("in_excess_window"),
        )

        bands_present = group_df["r:band"].unique().to_list()
        bands_present = [
            b for b in ["u", "g", "r", "i", "z", "y"] if b in bands_present
        ]

        n_bands = len(bands_present)
        fig, axes = plt.subplots(
            nrows=n_bands * 2,
            ncols=1,
            figsize=(9, 3.2 * n_bands),
            sharex=True,
            gridspec_kw={"height_ratios": [3, 1] * n_bands},
        )

        if n_bands == 1:
            axes = [axes[0], axes[1]]

        for i, band in enumerate(bands_present):
            flux_ax = axes[2 * i]
            pull_ax = axes[2 * i + 1]

            band_df = group_df.filter(pl.col("r:band") == band)

            if band_df.height == 0:
                continue

            times = band_df["r:midpointMjdTai"].to_numpy()
            flux = band_df["r:psfFlux"].to_numpy()
            fluxerr = band_df["r:psfFluxErr"].to_numpy()
            xvals = band_df["phase_rest"].to_numpy()  # use rest-frame axis
            in_window = band_df["in_excess_window"].to_numpy()

            sncosmo_band = BAND_MAP[band]

            model_flux = np.array(
                [model.bandflux(sncosmo_band, t, zp=31.4, zpsys="ab") for t in times]
            )

            pull = (flux - model_flux) / fluxerr

            # smooth model curve
            t_grid = np.linspace(times.min() - 5, times.max() + 5, 300)
            x_grid = (t_grid - t0) / (1.0 + z_used)
            model_grid = np.array(
                [model.bandflux(sncosmo_band, t, zp=31.4, zpsys="ab") for t in t_grid]
            )

            color = BAND_COLORS[band]

            # Plot points outside window: faded
            outside = ~in_window
            if np.any(outside):
                flux_ax.errorbar(
                    xvals[outside],
                    flux[outside],
                    yerr=fluxerr[outside],
                    fmt="o",
                    color=color,
                    alpha=0.3,
                    capsize=2,
                )

            # Plot points inside window: opaque
            if np.any(in_window):
                flux_ax.errorbar(
                    xvals[in_window],
                    flux[in_window],
                    yerr=fluxerr[in_window],
                    fmt="o",
                    color=color,
                    alpha=1.0,
                    capsize=4,
                )

            flux_ax.plot(x_grid, model_grid, color=color)
            flux_ax.axhline(0, linestyle="--")
            flux_ax.set_ylabel(r"flux ($ZP_{AB}=25.0$)")
            flux_ax.text(
                0.95,
                0.88,
                f"lsst{band}",
                transform=flux_ax.transAxes,
                ha="right",
                va="top",
            )

            # pull panel
            if np.any(outside):
                pull_ax.scatter(
                    xvals[outside],
                    pull[outside],
                    color=color,
                    alpha=0.3,
                )

            if np.any(in_window):
                pull_ax.scatter(
                    xvals[in_window],
                    pull[in_window],
                    color=color,
                    alpha=1.0,
                )

            pull_ax.axhline(0, color="black")
            pull_ax.axhline(3, alpha=0.3)
            pull_ax.axhline(5, alpha=0.5)
            pull_ax.axhline(-3, alpha=0.3)
            pull_ax.axhline(-5, alpha=0.5)
            pull_ax.set_ylabel("pull")

            # Excess-window lines in rest-frame phase
            left_edge = (t_fd - t0) / (1.0 + z_used)
            right_edge = left_edge + 4.0

            flux_ax.axvline(left_edge, linestyle=":")
            flux_ax.axvline(right_edge, linestyle=":")
            pull_ax.axvline(left_edge, linestyle=":")
            pull_ax.axvline(right_edge, linestyle=":")

        axes[-1].set_xlabel("Rest-frame days since SALT3 B-band peak")

        fig.suptitle(object_id, y=0.995)

        summary_text = (
            f"z = {z_used:.6f}\n"
            f"$t_0$ = {t0:.2f}\n"
            f"$x_0$ = {x0:.6e}\n"
            f"$x_1$ = {x1:.3f}\n"
            f"$c$ = {c:.3f}\n"
            f"$t_{{fd}}$ = {t_fd:.2f}"
        )
        fig.text(0.02, 0.98, summary_text, va="top")

        plt.tight_layout(rect=[0, 0, 1, 0.97])
        if plot_output_path is not None:
            fig.savefig(plot_output_path / f"{object_id}_eex_diagnostic.png", dpi=200)
        plt.show()
        plt.close(fig)


def walkers_chain_plot(
    sampler_results: emcee.EnsembleSampler,
    labels: list[str],
    discard: int = 0,
    output_path: Path | None = None,
) -> None:
    """Plot the walkers behaviour as a function of the chain length to see how they converge and if there is any degeneracies between the parameters.

    Args:
        sampler_results (emcee.EnsembleSampler): The results from the sampling process which is the second index of the result from the fitting power law function.
        labels (list[str]): List of labels that are used for the labels of the y axis for the plot.
        discard (int, optional): The number of steps to discard before doing the plotting. Defaults to 0.
        output_path (Path | None, optional): Output path to where the plot can be saved if desired. Defaults to None.
    """

    samples = sampler_results.get_chain(
        discard=discard,
    )

    (
        nsteps,
        _nwalkers,
        ndim,
    ) = samples.shape

    _fig, axes = plt.subplots(
        ndim,
        1,
        figsize=(10, 2 * ndim),
        sharex=True,
    )

    if ndim == 1:
        axes = [axes]

    for i in range(ndim):
        ax = axes[i]
        ax.plot(samples[:, :, i], "k", alpha=0.3)
        ax.set_xlim(
            0,
            nsteps,
        )
        if labels:
            ax.set_ylabel(labels[i])

    axes[-1].set_xlabel("Step Number")
    plt.tight_layout()
    if output_path is not None:
        plt.savefig(
            output_path,
        )
    plt.show()


def fit_sample_parameters_plot(
    pl_fit_params_df: pl.DataFrame,
    rest_frame_no_eex: pl.DataFrame,
    window_length: int,
    full_rest_data_df: pl.DataFrame,
    output_path: Path | None = None,
) -> None:
    """Plots the median sampled values from the sampling of parameters for the power law against the real data of the light curves of the objects.

    Args:
        pl_fit_params_df (pl.DataFrame): The results of the chain from the sampling of the power law, this should be the resulting dataframe output from the power law fitting function.
        output_path (Path | None, optional): Desired output path for the plots of the input polars df. Defaults to None.
    """

    for object_id, object_df in pl_fit_params_df[0].group_by("r:diaObjectId"):
        diaObjectId = object_df["r:diaObjectId"].item()

        rest_band_data = {}

        band_data = {}

        for current_band in [
            "g",
            "r",
            "i",
        ]:
            # Filter for the light curve data of this object in the desired band too.
            rest_band_df = full_rest_data_df.filter(
                (pl.col("r:band") == current_band)
                & (pl.col("r:diaObjectId") == diaObjectId),
            )

            if rest_band_df.height > 0:
                rest_band_data[current_band] = {
                    "times": rest_band_df["rest_frame_time"].to_numpy(),
                    "flux": rest_band_df["r:psfFlux"].to_numpy(),
                    "flux_error": rest_band_df["r:psfFluxErr"].to_numpy(),
                }

            band_df = rest_frame_no_eex.filter(
                (pl.col("r:band") == current_band)
                & (pl.col("r:diaObjectId") == diaObjectId),
            )

            if band_df.height > 0:
                band_data[current_band] = {
                    # Making Numpy arrays of the columns for the iteration and fitting.
                    "times": band_df["rest_frame_time"].to_numpy(),
                    "flux": band_df["r:psfFlux"].to_numpy(),
                    "flux_error": band_df["r:psfFluxErr"].to_numpy(),
                }

        fit_bands = list(band_data.keys())

        # Grabbing the time of first detection for the object
        model_parameters = {}

        for band in fit_bands:
            model_parameters[band] = {
                "A_prime": object_df[f"A_prime_{band}"].item(),
                "alpha": object_df[f"alpha_{band}"].item(),
            }

        t_fl_med = object_df["t_fl"].item()
        t_fd_rest = object_df["t_fd_rest"].item()

        model_grids = {}

        for band in fit_bands:
            times = band_data[band]["times"]

            model_grids[band] = np.linspace(
                np.min(times),
                np.max(times),
                300,
            )

        model_flux = {}

        for band in fit_bands:
            model_flux[band] = power_law_model(
                times=model_grids[band],
                t_fl=t_fl_med,
                A_prime=model_parameters[band]["A_prime"],
                alpha=model_parameters[band]["alpha"],
            )

        (
            _fig,
            (axes_fit, axes_resid),
        ) = plt.subplots(
            nrows=2,
            ncols=1,
            sharex=True,
            height_ratios=[3, 1],
            figsize=(8, 5),
        )

        for band in fit_bands:
            times = rest_band_data[band]["times"]
            flux = rest_band_data[band]["flux"]
            flux_error = rest_band_data[band]["flux_error"]

            in_ranges = (times >= t_fd_rest) & (times <= t_fd_rest + window_length)

            plot_data = axes_fit.errorbar(
                x=times[in_ranges],
                y=flux[in_ranges],
                yerr=flux_error[in_ranges],
                fmt="o",
                capsize=3,
                mec="white",
                mew=1,
                alpha=0.3,
            )

            data_colour = plot_data.lines[0].get_color()

            axes_fit.errorbar(
                x=times[~in_ranges],
                y=flux[~in_ranges],
                yerr=flux_error[~in_ranges],
                fmt="o",
                capsize=3,
                mec="white",
                color=data_colour,
                mew=1,
                label=f"lsst{band}",
            )

            axes_fit.plot(
                model_grids[band],
                model_flux[band],
                color=data_colour,
            )

            # Model evaluated at the actual observation times
            model_at_data = power_law_model(
                times=times,
                t_fl=t_fl_med,
                A_prime=model_parameters[band]["A_prime"],
                alpha=model_parameters[band]["alpha"],
            )

            residuals = (flux - model_at_data) / (flux_error)

            axes_resid.errorbar(
                x=times[in_ranges],
                y=residuals[in_ranges],
                fmt="o",
                capsize=3,
                mec="white",
                color=data_colour,
                mew=1,
            )

            axes_resid.errorbar(
                x=times[~in_ranges],
                y=residuals[~in_ranges],
                fmt="o",
                capsize=3,
                mec="white",
                alpha=0.3,
                color=data_colour,
                mew=1,
            )

        axes_resid.axhline(
            c="black",
        )

        axes_resid.axhspan(
            -5,
            5,
            color="grey",
            linestyle=":",
            alpha=0.12,
            label=r"$5 \sigma$ region",
        )

        axes_resid.axhspan(
            -3,
            3,
            color="grey",
            linestyle="--",
            alpha=0.25,
            label=r"$3 \sigma$ region",
        )

        axes_fit.axvline(
            x=t_fd_rest,
            linestyle="--",
            label=rf"$t_{{fd}}={t_fd_rest:.2f}$ d",
            color="#0072B2",
        )

        axes_fit.axvline(
            x=t_fd_rest + window_length,
            linestyle=":",
            label=rf"$t_{{fd}} + {window_length} ={t_fd_rest + window_length:.2f}$ d",
            color="#0072B2",
        )

        axes_resid.axvline(
            x=t_fd_rest,
            linestyle="--",
            label=rf"$t_{{fd}}={t_fd_rest:.2f}$ d",
            color="#0072B2",
        )

        axes_resid.axvline(
            x=t_fd_rest + window_length,
            linestyle=":",
            label=rf"$t_{{fd}} + {window_length} ={t_fd_rest + window_length:.2f}$ d",
            color="#0072B2",
        )

        axes_fit.axvline(
            t_fl_med,
            linestyle="--",
            label=rf"$t_{{\mathrm{{fl}}}}={t_fl_med:.2f}$ d",
            color="#D55E00",
        )

        axes_fit.set_ylabel("Flux (nJy)")
        axes_fit.set_title(f"{diaObjectId}")
        axes_resid.set_xlabel(r"Rest-frame days since $B$-band peak")
        axes_resid.set_ylabel("Pull")
        axes_fit.legend(
            loc="best",
            frameon=False,
        )
        plt.tight_layout()
        if output_path is not None:
            plt.savefig(output_path / f"{diaObjectId}_eex_power_law_fit.jpg")
        plt.show()
        plt.close()
